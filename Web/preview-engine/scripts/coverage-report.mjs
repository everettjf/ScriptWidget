// Writes docs/browser-preview-coverage.md from src/render/coverage.js.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { coverage, generalProps } from "../src/render/coverage.js";
import { engineVersion } from "../src/contract.js";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../../..");
export function coverageMarkdown() {
  const row = (name, entry) => `| \`${name}\` | ${entry.state} | ${entry.note || ""} |`;
  const lines = [
    "# Browser preview coverage",
    "",
    `Generated by \`Web/preview-engine/scripts/coverage-report.mjs\` for preview engine ${engineVersion}. Do not edit by hand.`,
    "States: **supported** renders like iPhone within measured tolerances; **approximated** renders with the noted difference; **unsupported** shows a placeholder and a diagnostic. Properties not listed for a tag are ignored by the native runtime and reported as such.",
    "",
    "## Tags",
    "",
    "| Tag | State | Note |",
    "| --- | --- | --- |",
    ...Object.entries(coverage.tags).map(([tag, entry]) => row(tag, entry)),
    "",
    "## General modifier properties",
    "",
    "Applied by every tag except `spacer` (frame only) and `Fragment`, in this order: padding, frame, background, corner, clip, opacity, animation, rotation, rotation3d, shadow.",
    "",
    "| Property | State | Note |",
    "| --- | --- | --- |",
    ...Object.entries(generalProps).map(([key, entry]) => row(key, entry)),
    "",
    "## Tag properties",
    "",
    "| Tag | Property | State | Note |",
    "| --- | --- | --- | --- |",
    ...Object.entries(coverage.tags).flatMap(([tag, entry]) => Object.entries(entry.props).map(([key, prop]) => `| \`${tag}\` | \`${key}\` | ${prop.state} | ${prop.note || ""} |`)),
    "",
  ];
  return lines.join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  fs.writeFileSync(path.join(root, "docs/browser-preview-coverage.md"), coverageMarkdown());
  console.log("docs/browser-preview-coverage.md written");
}
