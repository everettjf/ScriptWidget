// Writes Web/preview-engine/src/render/symbolMetrics.generated.js: the
// width and height of every SF Symbol in scripts/icons/sf-to-lucide.json at
// 100 points, measured with SwiftUI. SF Symbols scale linearly with the font
// size, so the web renderer sizes its look-alike icons from these ratios.
//
//   swiftc -parse-as-library -o /tmp/symbol-metrics Tools/ScriptWidgetPreview/Scripts/symbol-metrics.swift
//   /tmp/symbol-metrics <repository root>
import SwiftUI

@main
struct SymbolMetrics {
    @MainActor static func main() throws {
        let root = URL(fileURLWithPath: CommandLine.arguments.count > 1 ? CommandLine.arguments[1] : FileManager.default.currentDirectoryPath)
        let mapURL = root.appendingPathComponent("Web/preview-engine/scripts/icons/sf-to-lucide.json")
        let names = try (JSONSerialization.jsonObject(with: Data(contentsOf: mapURL)) as? [String: String] ?? [:]).keys.sorted()
        var lines: [String] = []
        for name in names + ["questionmark.circle"] where !lines.contains(where: { $0.hasPrefix("  \"\(name)\":") }) {
            let size = NSHostingController(rootView: Image(systemName: name).font(.system(size: 100)).fixedSize().environment(\.displayScale, 2))
                .sizeThatFits(in: CGSize(width: 100_000, height: 100_000))
            guard size.width > 0 else { continue }
            lines.append(String(format: "  \"%@\": [%g, %g],", name, size.width / 100, size.height / 100))
        }
        let output = """
        // Generated by Tools/ScriptWidgetPreview/Scripts/symbol-metrics.swift; do not edit.
        // SF Symbol width and height per point of font size (SwiftUI, regular weight).
        export const symbolMetrics = Object.freeze({
        \(lines.joined(separator: "\n"))
        });

        """
        try output.write(to: root.appendingPathComponent("Web/preview-engine/src/render/symbolMetrics.generated.js"), atomically: true, encoding: .utf8)
        print("\(lines.count) symbols")
    }
}
