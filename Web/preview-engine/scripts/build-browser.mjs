// Builds dist/sandbox-sources.js (the sandboxed frame document with its two
// Worker sources inlined) and copies the runtime support scripts to
// dist/assets/. No bundler: the inlined modules are dependency-free.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { scriptWidgetKernel } from "../src/kernel.js";
import { executorBootstrap } from "../src/browser/executorBootstrap.js";
import { compilerBootstrap } from "../src/browser/compilerBootstrap.js";
import { sandboxFrame } from "../src/browser/sandboxFrame.js";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const supportDirectory = path.resolve(root, "../../Shared/ScriptWidgetRuntime/Widget/Resource/support.bundle");
const output = path.join(root, "dist");

export const sandboxPolicy = [
  "default-src 'none'",
  // Inline frame script, plus blob: Workers and the classic scripts they load.
  // 'unsafe-eval' keeps eval/new Function parity with JavaScriptCore.
  "script-src 'unsafe-inline' 'unsafe-eval' blob:",
  "worker-src blob:",
  "connect-src 'none'",
  "img-src 'none'",
  "style-src 'none'",
  "font-src 'none'",
  "base-uri 'none'",
  "form-action 'none'",
].join("; ");

function moduleBody(file) {
  return fs.readFileSync(path.join(root, "src", file), "utf8")
    .replace(/^import[^;]+;\n/gm, "")
    .replace(/^export \{[^}]*\}[^;]*;\n/gm, "")
    .replace(/^export (const|function|async function|class) /gm, "$1 ");
}

export function buildSandboxSources() {
  const prepareBundle = `const prepare = (function () {\n${["contract.js", "packageFiles.js", "compiler.js", "prepare.js"].map(moduleBody).join("\n")}\nreturn { createCompiler, preparePackage };\n})();\n`;
  const compilerWorkerSource = `${prepareBundle}(${compilerBootstrap.toString()})(prepare);\n`;
  const executorWorkerSource = `(${executorBootstrap.toString()})(${scriptWidgetKernel.toString()});\n`;
  const literal = (value) => JSON.stringify(value).replace(/<\//g, "<\\/").replace(/<!--/g, "<\\!--");
  const sandboxDocument = `<!doctype html><html><head><meta charset="utf-8"><meta http-equiv="Content-Security-Policy" content="${sandboxPolicy}"></head><body><script>(${sandboxFrame.toString()})(${literal(compilerWorkerSource)}, ${literal(executorWorkerSource)});</script></body></html>`;
  return { sandboxDocument, compilerWorkerSource, executorWorkerSource };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { sandboxDocument } = buildSandboxSources();
  fs.mkdirSync(path.join(output, "assets"), { recursive: true });
  fs.writeFileSync(path.join(output, "sandbox-sources.js"), `// Generated by scripts/build-browser.mjs. Do not edit.\nexport const sandboxDocument = ${JSON.stringify(sandboxDocument)};\n`);
  for (const name of ["core.js", "util.js", "moment.min.js"]) {
    fs.copyFileSync(path.join(supportDirectory, name), path.join(output, "assets", name));
  }
  const { corpusPackages, readNativeTrees, usesLiveData } = await import("../test/parity/corpus.js");
  const { readPackageDirectory, readPackageResources } = await import("../src/node.js");
  const native = readNativeTrees();
  const corpus = corpusPackages().map(({ name, directory }) => ({ name, files: readPackageDirectory(directory), resources: readPackageResources(directory), expected: native.entries[name] }))
    .filter((item) => !usesLiveData(item.files["main.jsx"]));
  const prelude = fs.readFileSync(path.join(root, "test/parity/prelude.js"), "utf8");
  fs.writeFileSync(path.join(output, "parity-corpus.json"), JSON.stringify({ timeZone: native.timeZone, prelude, corpus }));
  console.log(`dist/sandbox-sources.js ${(sandboxDocument.length / 1024).toFixed(1)} KiB`);
}
