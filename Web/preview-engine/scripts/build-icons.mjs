// Generates src/render/icons.generated.js from lucide-static's icon-nodes.json
// for the SF Symbol names in scripts/icons/sf-to-lucide.json.
// Usage: node scripts/build-icons.mjs <path-to-lucide-static-package>
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const lucide = process.argv[2];
if (!lucide) throw new Error("Pass the lucide-static package directory");
const nodes = JSON.parse(fs.readFileSync(path.join(lucide, "icon-nodes.json"), "utf8"));
const version = JSON.parse(fs.readFileSync(path.join(lucide, "package.json"), "utf8")).version;
const mapping = JSON.parse(fs.readFileSync(path.join(root, "scripts/icons/sf-to-lucide.json"), "utf8"));
const allowed = new Set(["path", "circle", "rect", "line", "polyline", "polygon", "ellipse"]);
const attributes = new Set(["d", "cx", "cy", "r", "rx", "ry", "x", "y", "x1", "y1", "x2", "y2", "width", "height", "points"]);
const icons = {};
for (const [symbol, name] of Object.entries(mapping)) {
  if (!nodes[name]) throw new Error(`Lucide has no icon "${name}" for ${symbol}`);
  icons[name] = nodes[name].map(([tag, attrs]) => {
    if (!allowed.has(tag)) throw new Error(`Unexpected element ${tag} in ${name}`);
    return [tag, Object.fromEntries(Object.entries(attrs).filter(([key]) => attributes.has(key)))];
  });
}
const license = fs.readFileSync(path.join(lucide, "LICENSE"), "utf8").trim();
const output = `// Generated by scripts/build-icons.mjs from lucide-static ${version}. Do not edit.
/*
${license}
*/
export const lucideVersion = ${JSON.stringify(version)};
export const sfSymbolToLucide = ${JSON.stringify(mapping)};
export const lucideIcons = ${JSON.stringify(icons)};
`;
fs.writeFileSync(path.join(root, "src/render/icons.generated.js"), output);
console.log(`${Object.keys(mapping).length} symbols -> ${Object.keys(icons).length} icons`);
